export const getLang = () => (getPrefs().lang === 'en' ? 'en' : 'id');
export const locale = () => (getLang() === 'en' ? 'en-GB' : 'id-ID');

/** Ambil teks sesuai bahasa aktif; {nama} diganti dari `vars`. */
export function t(key, vars = {}) {
  const text = DICT[getLang()][key] ?? DICT.id[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

/** Terjemahkan elemen statis di index.html (data-i18n, data-i18n-aria). */
export function translateStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((n) => { n.textContent = t(n.dataset.i18n); });
  root.querySelectorAll('[data-i18n-aria]').forEach((n) => n.setAttribute('aria-label', t(n.dataset.i18nAria)));
  document.documentElement.lang = getLang();
}
